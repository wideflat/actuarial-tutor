export const COLORS: Record<TetrominoType, string> = {
  I: '#00f0f0',
  O: '#f0f000',
  T: '#a000f0',
  S: '#00f000',
  Z: '#f00000',
  J: '#0000f0',
  L: '#f0a000',
};

// Color index mapping (1-7 stored on board)
export const COLOR_INDEX: TetrominoType[] = ['I', 'O', 'T', 'S', 'Z', 'J', 'L'];

export const getShape = (type: TetrominoType, rotation: number): number[][] =>
  SHAPES[type][rotation % 4];

export const getColorIndex = (type: TetrominoType): number =>
  COLOR_INDEX.indexOf(type) + 1;

export const getColorByIndex = (index: number): string => {
  if (index === 0) return 'transparent';
  return COLORS[COLOR_INDEX[index - 1]] ?? 'transparent';
};

export const ALL_TYPES: TetrominoType[] = ['I', 'O', 'T', 'S', 'Z', 'J', 'L'];
